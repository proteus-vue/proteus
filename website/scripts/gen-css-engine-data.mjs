#!/usr/bin/env node
// website/scripts/gen-css-engine-data.mjs —— ★★★Themis（CSS 引擎）产品页的**数据同源生成器**
//
// 【为什么需要（官网既有纪律：每个数字都可追溯，不手抄）】`/themis` 产品页要展示 IR 字段、
//   逐属性对拍、M1 覆盖率、lint 棘轮、能力清单——这些全是**机器产物**（`docs/generated/
//   css-engine-numbers.json`，由 `scripts/gen-css-engine-numbers.mjs` 从各源读出）。
//   页面若手写数字，产物一动页面就"说谎"（本仓亲历：白皮书 §6 三处数字静默漂移、无门禁覆盖）。
//   ⇒ SSOT = `docs/generated/css-engine-numbers.json`；本脚本产出
//     `website/src/data/css-engine-page.ts`（生成物，勿手改）+ 把**四端真截图**复制到
//     `website/public/css-engine/`；`--check` 供 CI/verify 防漂移。
//
// 【截图是什么】`css-conformance/results/<end>/<page>.png` —— **同一份 SFC 编译产物**由各端
//   真实渲染器上屏后的整屏截图（Web 浏览器 / Android 真机 / iOS / 鸿蒙），已入库。
//   本脚本只**复制**（不重造设备链——那是 hosts/* 的职责）。
//
// 用法：node website/scripts/gen-css-engine-data.mjs          # 生成
//       node website/scripts/gen-css-engine-data.mjs --check  # 门禁（漂移 exit 1）
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const NUMBERS = path.join(ROOT, 'docs/generated/css-engine-numbers.json')
const CONF = path.join(ROOT, 'css-conformance/results')
const OUT_TS = path.join(ROOT, 'website/src/data/css-engine-page.ts')
const OUT_PUBLIC = path.join(ROOT, 'website/public/css-engine')

const CHECK = process.argv.includes('--check')

/**
 * ★四端演示截图（用户 2026-10-08「作为我们框架导航丝滑切换页面高性能渲染的案例」同一诉求的视觉证据）：
 *   挑两个**视觉信息量足**的验收页，各让**四端**真渲染——证明"同一份 SFC，四端长一个样"。
 *   public 目标名带连字符（避开框架平台变体后缀机制，同 consistency 页纪律）。
 */
const DEMO_PAGES = [
  { slug: 'border-style', zh: '边框线型 · dashed / dotted / 逐角圆角', en: 'Border style · dashed / dotted / per-corner radius' },
  { slug: 'background-position', zh: '背景定位 · size / position / repeat', en: 'Background position · size / position / repeat' },
]
const ENDS = [
  { end: 'web', zh: '浏览器 Web', en: 'Browser Web' },
  { end: 'android', zh: 'Android 真机', en: 'Android (device)' },
  { end: 'ios', zh: 'iOS', en: 'iOS' },
  { end: 'harmony', zh: '鸿蒙', en: 'HarmonyOS' },
]

function readJson(p, what) {
  if (!fs.existsSync(p)) {
    console.error(`[css-engine-data] ✗ 缺 ${what}：${path.relative(ROOT, p)}`)
    console.error('  （先生成：pnpm gen:css-engine-numbers）')
    process.exit(2)
  }
  return JSON.parse(fs.readFileSync(p, 'utf-8'))
}

const numbers = readJson(NUMBERS, 'Themis 数字 SSOT')

/* ── ① 组装数据（全部来自机器产物；无任何手写数字） ── */
const shots = []
for (const page of DEMO_PAGES) {
  for (const e of ENDS) {
    shots.push({
      page: page.slug,
      end: e.end,
      src: `css-conformance/results/${e.end}/${page.slug}.png`,
      pub: `${page.slug}-${e.end}.png`,
      labelZh: e.zh,
      labelEn: e.en,
    })
  }
}

const DATA = {
  generatedFrom: [
    'docs/generated/css-engine-numbers.json',
    'css-conformance/results/{web,android,ios,harmony}/*.png',
  ],
  /** 机器数字（原样来自 SSOT——页面按需渲染，不在此重算） */
  numbers,
  /** 四端真渲染截图清单（page × end） */
  demoPages: DEMO_PAGES.map((p) => ({ slug: p.slug, zh: p.zh, en: p.en })),
  shots,
}

/* ── ② TS 模块（确定性：无时间戳，同源 ⇒ 同字节） ── */
const ts = `// ⚠️ AUTO-GENERATED by website/scripts/gen-css-engine-data.mjs — DO NOT EDIT.
// SSOT：${DATA.generatedFrom.join(' · ')}
// 重新生成：pnpm gen:css-engine-data · 防漂移门禁：pnpm check:css-engine-data
export const CSS_ENGINE_PAGE = ${JSON.stringify(DATA, null, 2)} as const
`

/* ── ③ 截图复制（源 → public；--check 只比对字节） ── */
function syncShot(shot) {
  const src = path.join(ROOT, shot.src)
  const dst = path.join(OUT_PUBLIC, shot.pub)
  if (!fs.existsSync(src)) {
    console.error(`[css-engine-data] ✗ 缺截图：${shot.src}`)
    process.exit(2)
  }
  const buf = fs.readFileSync(src)
  if (CHECK) {
    if (!fs.existsSync(dst) || !buf.equals(fs.readFileSync(dst))) {
      console.error(`[css-engine-data] ✗ 截图漂移：${path.relative(ROOT, dst)} 与源不一致（跑 pnpm gen:css-engine-data）`)
      process.exit(1)
    }
  } else {
    fs.mkdirSync(OUT_PUBLIC, { recursive: true })
    fs.writeFileSync(dst, buf)
  }
}

if (CHECK) {
  const prev = fs.existsSync(OUT_TS) ? fs.readFileSync(OUT_TS, 'utf-8') : ''
  if (prev !== ts) {
    console.error('[css-engine-data] ✗ 页面数据漂移：website/src/data/css-engine-page.ts 与机器产物不一致（跑 pnpm gen:css-engine-data）')
    process.exit(1)
  }
  for (const s of DATA.shots) syncShot(s)
  console.log(`[css-engine-data] ✅ Themis 页数据与机器产物一致（IR ${numbers.ir.total} · 对拍 ${numbers.parity.cases}/${numbers.parity.props} · 四端截图 ${DATA.shots.length} 张）`)
} else {
  fs.mkdirSync(path.dirname(OUT_TS), { recursive: true })
  fs.writeFileSync(OUT_TS, ts)
  for (const s of DATA.shots) syncShot(s)
  console.log(`[css-engine-data] ✅ 生成 website/src/data/css-engine-page.ts（${ts.length}B）+ 复制 ${DATA.shots.length} 张四端截图 → website/public/css-engine/`)
}
