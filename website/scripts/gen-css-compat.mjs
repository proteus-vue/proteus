// gen-css-compat.mjs —— CSS 兼容规则参考页生成器（SSOT = packages/css-compat/src/rules.ts CSS_RULES + budget.ts CSS_BUDGETS）
// 生成：content/reference/css-compat.md（规则逐条：code/name/severity/description/fixable + 检测维度）
// 用法：node scripts/gen-css-compat.mjs [--check]（--check 漂移检测，不一致 exit 1）
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'content', 'reference', 'css-compat.md')
const check = process.argv.includes('--check')

const RULES_URL = pathToFileURL(path.join(ROOT, '..', 'packages', 'css-compat', 'src', 'rules.ts')).href
const BUDGET_URL = pathToFileURL(path.join(ROOT, '..', 'packages', 'css-compat', 'src', 'budget.ts')).href

const rulesMod = await import(RULES_URL)
const budgetMod = await import(BUDGET_URL)
const CSS_RULES = rulesMod.CSS_RULES
const CSS_BUDGETS = budgetMod.CSS_BUDGETS

/** 检测维度归纳（从 check 函数名推导：checkSelector/checkDeclaration/checkAtRule） */
function dimensions(rule) {
  const dims = []
  if (rule.checkSelector) dims.push('选择器')
  if (rule.checkDeclaration) dims.push('声明')
  if (rule.checkAtRule) dims.push('@rule')
  return dims.join(' / ') || '—'
}

function render() {
  const out = []
  out.push('---')
  out.push('title: CSS 跨端兼容规则')
  out.push('order: 42')
  out.push('group: 工程参考')
  out.push('generated: true')
  out.push('---')
  out.push('')
  out.push('# CSS 跨端兼容规则')
  out.push('')
  out.push(`> ${CSS_RULES.length} 条规则——SSOT = \`packages/css-compat/src/rules.ts\` \`CSS_RULES\`（数据驱动注册表，postcss AST 遍历按序执行），与 \`proteus css:check\` 同源。`)
  out.push('')
  out.push('## 规则清单')
  out.push('')
  out.push('| code | 规则 | 级别 | 检测维度 | 可自动修复 | 说明 |')
  out.push('|---|---|---|---|---|---|')
  for (const r of CSS_RULES) {
    const dims = dimensions(r)
    out.push(`| ${r.code} | ${r.name} | ${r.severity} | ${dims} | ${r.fixable ? '✅' : '—'} | ${r.description} |`)
  }
  out.push('')
  out.push('## 逐条说明')
  out.push('')
  for (const r of CSS_RULES) {
    out.push(`### ${r.code} ${r.name}`)
    out.push('')
    out.push(`- **级别**：${r.severity}（strict 模式 error 阻断 / warn 警告）`)
    out.push(`- **可自动修复**：${r.fixable ? '是' : '否'}`)
    out.push(`- **说明**：${r.description}`)
    out.push('')
  }
  out.push('## 体积预算（CSS_BUDGETS）')
  out.push('')
  out.push('| 指标 | 上限/下限 | 方向 |')
  out.push('|---|---|---|')
  for (const b of CSS_BUDGETS) {
    out.push(`| ${b.label} | ${b.limit} | ${b.direction === 'max' ? '≤' : '≥'} |`)
  }
  out.push('')
  out.push('> 规则执行：`proteus css:check [dir|file]`（postcss AST 遍历按序执行；--report 落盘结构化报告）')
  out.push('')
  out.push('<!-- generated by website/scripts/gen-css-compat.mjs · 源码 SSOT：packages/css-compat/src/rules.ts CSS_RULES + budget.ts CSS_BUDGETS -->')
  return out.join('\n')
}

const md = render()

if (check) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null
  if (committed === md) {
    console.log('CHECK OK — CSS 兼容规则与源一致')
  } else {
    console.error('DRIFT: content/reference/css-compat.md 与 CSS_RULES 源不一致——运行 npm run gen:css-compat 并提交')
    process.exit(1)
  }
} else {
  fs.writeFileSync(OUT, md)
  console.log(`generated: content/reference/css-compat.md（${CSS_RULES.length} 规则 + ${CSS_BUDGETS.length} 预算指标）`)
}
