// gen-reference.mjs —— 参考文档生成器（G-60 B2 文档自动化体系扩展）
// 生成两页（SSOT = CLI/编译器源码，业务零手写）：
//   content/reference/cli.md          ← packages/cli/src/args.ts HELP_GROUPS（命令分组+usage+desc）
//   content/reference/rules.md        ← @proteus-vue/compiler TRANSFORM_RULES（67 条规则 AI 说明书）
// 用法：node scripts/gen-reference.mjs [--check]（--check 漂移检测：不一致 exit 1）
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'content', 'reference')
const check = process.argv.includes('--check')

// —— SSOT 加载（tsx 模式直接 import TS 源，与 gen-content.mjs 同法） ——
async function loadCliHelp() {
  // HELP_GROUPS 在 args.ts（纯数据 TS）——用 tsx 转译加载不可行（node 环境），改读源码 + 正则提取
  // 结构稳定（HelpGroup[]: { title, titleEn?, entries: [{ usage, desc, descEn? }] }），正则按 entries 块切分
  const src = fs.readFileSync(path.join(ROOT, '..', 'packages', 'cli', 'src', 'args.ts'), 'utf8')
  const groups = []
  const groupRe = /title:\s*'([^']+)'\s*,\s*(?:titleEn:\s*'([^']*)'\s*,\s*)?entries:\s*\[([\s\S]*?)\]\s*,?\s*\}/g
  let gm
  while ((gm = groupRe.exec(src))) {
    const title = gm[1]
    const titleEn = gm[2] || undefined
    const body = gm[3]
    const entries = []
    const entryRe = /usage:\s*'([^']+)'\s*,\s*desc:\s*'((?:[^'\\]|\\.)*)'\s*,\s*(?:descEn:\s*'((?:[^'\\]|\\.)*)'\s*,?)?/g
    let em
    while ((em = entryRe.exec(body))) {
      entries.push({ usage: em[1], desc: em[2].replaceAll('\\n', '\n'), descEn: em[3] === undefined ? undefined : em[3].replaceAll('\\n', '\n') })
    }
    if (entries.length) groups.push({ title, titleEn, entries })
  }
  return groups
}

async function loadRules() {
  // TRANSFORM_RULES 经编译器导出面消费——运行时用已构建 dist（tsx import TS 源亦可，与 gen-content 同法）
  const mod = await import(pathToFileURL(path.join(ROOT, '..', 'packages', 'compiler', 'src', 'transforms', 'registry.ts')).href)
  return mod.listTransformRules()
}

// —— 渲染：CLI 参考 ——
function renderCli(groups) {
  const out = []
  out.push('---')
  out.push('title: CLI 命令参考')
  out.push('order: 40')
  out.push('group: 工程命令')
  out.push('generated: true')
  out.push('---')
  out.push('')
  out.push('# CLI 命令参考')
  out.push('')
  out.push(`> 本页由 CLI 命令注册表自动生成（\`packages/cli/src/args.ts\` HELP_GROUPS，\`website/scripts/gen-reference.mjs\`），请勿手工编辑。`)
  out.push('')
  for (const g of groups) {
    out.push(`## ${g.title}`)
    out.push('')
    for (const e of g.entries) {
      out.push(`### \`${e.usage.split(' ').slice(0, 2).join(' ')}\``)
      out.push('')
      out.push('```bash')
      out.push(e.usage)
      out.push('```')
      out.push('')
      if (e.desc) out.push(e.desc, '')
    }
  }
  out.push('<!-- generated by website/scripts/gen-reference.mjs · 源码 SSOT：packages/cli/src/args.ts HELP_GROUPS -->')
  return out.join('\n')
}

// —— ★#484 CLI 参考 EN overlay（字段 = args.ts HELP_GROUPS 的 titleEn/descEn；usage 元变量占位替换） ——
const USAGE_TOKEN_EN = [
  ['<族>', '<family>'],
  ['<cli 路径>', '<cli path>'],
  ['<模块>', '<module>'],
  ['<vue 文件 | 规则 ID>', '<vue file | rule ID>'],
]
function usageEnOf(usage) {
  let s = usage
  for (const [z, e] of USAGE_TOKEN_EN) s = s.split(z).join(e)
  return s
}
function renderCliEn(groups) {
  const out = []
  out.push('---')
  out.push('title: CLI command reference')
  out.push('order: 40')
  out.push('group: 工程命令')
  out.push('generated: true')
  out.push('---')
  out.push('')
  out.push('# CLI command reference')
  out.push('')
  out.push('> Generated from the CLI command registry (`packages/cli/src/args.ts` HELP_GROUPS, `website/scripts/gen-reference.mjs`) — do not hand-edit.')
  out.push('')
  for (const g of groups) {
    out.push(`## ${g.titleEn ?? g.title}`)
    out.push('')
    for (const e of g.entries) {
      out.push(`### \`${usageEnOf(e.usage).split(' ').slice(0, 2).join(' ')}\``)
      out.push('')
      out.push('```bash')
      out.push(usageEnOf(e.usage))
      out.push('```')
      out.push('')
      if (e.descEn ?? e.desc) out.push(e.descEn ?? e.desc, '')
    }
  }
  out.push('<!-- generated by website/scripts/gen-reference.mjs (en overlay) · source SSOT: packages/cli/src/args.ts HELP_GROUPS -->')
  return out.join('\n')
}

// —— 渲染：编译规则目录 ——
const PHASE_EN = { template: 'Template transforms', script: 'Script transforms', style: 'Style transforms', validate: 'Output validation' }
function renderRules(rules) {
  const out = []
  out.push('---')
  out.push('title: 编译规则目录')
  out.push('order: 41')
  out.push('group: 工程命令')
  out.push('generated: true')
  out.push('---')
  out.push('')
  out.push('# 编译规则目录')
  out.push('')
  out.push(`> ${rules.length} 条编译规则——每条自带 AI 说明书（id / when / before → after / why）。SSOT = \`@proteus-vue/compiler\` TRANSFORM_RULES，与 \`npx proteus rules\` / Playground Trace 同源。`)
  out.push('')
  const phaseTitle = { template: '模板转换', script: '脚本转换', style: '样式转换', validate: '产物校验' }
  const byPhase = {}
  for (const r of rules) (byPhase[r.phase] ??= []).push(r)
  for (const phase of Object.keys(byPhase)) {
    out.push(`## ${phaseTitle[phase] ?? phase}（${byPhase[phase].length}）`)
    out.push('')
    for (const r of byPhase[phase]) {
      out.push(`### \`${r.id}\``)
      out.push('')
      out.push(`**${r.title}**`)
      out.push('')
      if (r.description) out.push(r.description, '')
      if (r.example) {
        out.push('```')
        out.push(`before: ${r.example.before ?? ''}`)
        out.push(`after:  ${r.example.after ?? ''}`)
        out.push('```')
        out.push('')
      }
      if (r.why) out.push(`> why: ${r.why}`, '')
    }
  }
  out.push('<!-- generated by website/scripts/gen-reference.mjs · 源码 SSOT：packages/compiler/src/transforms/registry.ts TRANSFORM_RULES -->')
  return out.join('\n')
}

