// —— main（生成 / --check 漂移） ——
fs.mkdirSync(OUT, { recursive: true })
const cliGroups = await loadCliHelp()
const rules = await loadRules()
const outputs = [
  { file: 'cli.md', md: renderCli(cliGroups), label: 'CLI 命令参考' },
  { file: 'rules.md', md: renderRules(rules), label: '编译规则目录' },
]

let drifts = 0
for (const o of outputs) {
  const p = path.join(OUT, o.file)
  if (check) {
    const committed = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null
    if (committed !== o.md) {
      drifts++
      console.error(`DRIFT: content/reference/${o.file} 与源不一致——运行 npm run gen:reference 并提交`)
    } else {
      console.log(`OK: ${o.file} 与源一致`)
    }
  } else {
    fs.writeFileSync(p, o.md)
    console.log(`generated: content/reference/${o.file}`)
  }
}
// ★#483/484 rules + cli EN overlay（css-compat 的 CSS 矩阵双语待排；--check 仅比对 zh 产物）
if (!check) {
  const OUT_EN = path.join(ROOT, 'en', 'reference')
  fs.mkdirSync(OUT_EN, { recursive: true })
  fs.writeFileSync(path.join(OUT_EN, 'rules.md'), renderRulesEn(rules))
  fs.writeFileSync(path.join(OUT_EN, 'cli.md'), renderCliEn(cliGroups))
  console.log('generated: en/reference/rules.md + cli.md')
}

if (check) {
  if (drifts) process.exit(1)
  console.log('CHECK OK — 参考文档与源一致')
} else {
  console.log(`\nOK: ${outputs.length} 个参考页已生成（--check 可做漂移门禁）`)
}
