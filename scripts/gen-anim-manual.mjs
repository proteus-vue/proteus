#!/usr/bin/env node
// scripts/gen-anim-manual.mjs —— ★Morpheus **动画声明项 AI 说明书**生成器 + conformance 门禁
//
// 【为什么生成（而不是手写文档）】Morpheus §13 执行指令第 11 条要求「每个预设与声明项必须配
//   conformance 断言 + AI 说明书」。手写文档必然漂移——本轮就实测到一处：
//   包 README 的曲线名写成 `snappy/customBezier`，而实现是 `easeIn/springApprox`（无人发现）。
//   ⇒ 说明书从 `packages/animation/src/rules.ts`（单一事实来源）生成，`--check` 接门禁。
//
// 【两道检查（都在本脚本里，一个入口）】
//   ① **conformance**：说明书 ↔ 实现/内核的**对账**（preset 真实存在 / 契约值一致 / verify 可追溯）；
//   ② **生成物一致性**：`docs/generated/anim-manual.md` 与本次生成逐字节一致（漂移即红）。
//
// 用法：
//   node scripts/gen-anim-manual.mjs          # 生成（写文件）
//   node scripts/gen-anim-manual.mjs --check  # 校验（CI / verify；漂移或 conformance 失败 ⇒ exit 1）
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const OUT = path.join(ROOT, 'docs/generated/anim-manual.md')
const CHECK = process.argv.includes('--check')

// ── ① 求值真实规则表（tsx 子进程；与 gen-instruction-spec / gen-capability-priority 同模式）──
const probe = `
import { ANIM_RULES, listAnimRules } from ${JSON.stringify(path.join(ROOT, 'packages/animation/src/rules.ts'))}
import { runConformance } from ${JSON.stringify(path.join(ROOT, 'packages/animation/src/conformance.ts'))}
console.log(JSON.stringify({ rules: ANIM_RULES, findings: runConformance() }))
`
const raw = execFileSync('npx', ['tsx', '-e', probe], { cwd: ROOT, encoding: 'utf-8', timeout: 120000 })
const { rules, findings } = JSON.parse(raw.trim().split('\n').pop())

// ── ② conformance 先判（说明书对不上实现 ⇒ 直接红，不生成误导性文档）──
const failures = findings.filter((f) => !f.ok)
if (failures.length > 0) {
  console.error('[anim-manual] ✗ conformance 未通过（说明书与实现不一致）：')
  for (const f of failures) console.error(`    · ${f.ruleId} [${f.check}] ${f.detail}`)
  process.exit(1)
}

// ── ③ 渲染 ──
const KIND_LABEL = {
  preset: '预设（可直接用）',
  primitive: '声明面原语（字段/取值）',
  constraint: '约束与陷阱（会静默出错）',
  boundary: '诚实边界（能做 / 不能做）',
}
const KIND_ORDER = ['preset', 'primitive', 'constraint', 'boundary']

const lines = []
lines.push('---')
lines.push('title: Morpheus 动画声明项 AI 说明书')
lines.push('order: 92')
lines.push('group: 框架能力')
lines.push('generated: true')
lines.push('---')
lines.push('')
lines.push('# Morpheus 动画声明项 AI 说明书')
lines.push('')
lines.push(`> **生成物，勿手改**：\`node scripts/gen-anim-manual.mjs\`（\`--check\` 接 CI，漂移即红）`)
lines.push(`> **单一事实来源**：\`packages/animation/src/rules.ts\` 的 \`ANIM_RULES\`（${rules.length} 条）`)
lines.push('>')
lines.push('> 本表与编译器的 111 条规则**同构**（Morpheus §13 第 11 条硬性要求）——')
lines.push('> 每条含 what / why / when / 示例 / 如何验证 / 实现位置，AI 可单独消费一条。')
lines.push('>')
lines.push('> **conformance**：本页生成前会跑 `runConformance()` 对账（预设真实存在 / 跨语言契约值一致 /')
lines.push('> `verify` 可追溯）——**对不上就不生成**，避免产出误导性文档。')
lines.push('')

for (const kind of KIND_ORDER) {
  const items = rules.filter((r) => r.kind === kind)
  if (items.length === 0) continue
  lines.push(`## ${KIND_LABEL[kind]}（${items.length} 条）`)
  lines.push('')
  for (const r of items) {
    lines.push(`### \`${r.id}\``)
    lines.push('')
    lines.push(`**${r.title}** \`[${r.status}]\``)
    lines.push('')
    lines.push(`- **是什么**：${r.description}`)
    lines.push(`- **为什么**：${r.why}`)
    lines.push(`- **何时用**：${r.when}`)
    if (r.decision) lines.push(`- **相关决策**：${r.decision}`)
    lines.push(`- **如何验证**：${r.verify}`)
    lines.push(`- **实现位置**：\`${r.source}\``)
    lines.push('')
    lines.push('```ts')
    lines.push(r.example)
    lines.push('```')
    lines.push('')
  }
}
lines.push('<!-- generated by scripts/gen-anim-manual.mjs · SSOT：packages/animation/src/rules.ts ANIM_RULES -->')
const content = lines.join('\n') + '\n'

// ── ④ 写 / 校验 ──
if (CHECK) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : ''
  if (existing !== content) {
    console.error(`[anim-manual] ✗ 生成物漂移：${path.relative(ROOT, OUT)}`)
    console.error('  ⇒ 跑 `node scripts/gen-anim-manual.mjs` 重新生成（改了 rules.ts 后必须重生成）')
    process.exit(1)
  }
  console.log(`[anim-manual] ✅ 说明书一致（${rules.length} 条 · conformance 通过 · ${path.relative(ROOT, OUT)}）`)
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, content)
  console.log(`[anim-manual] ✅ 生成 ${path.relative(ROOT, OUT)}（${rules.length} 条 · conformance 通过）`)
}
