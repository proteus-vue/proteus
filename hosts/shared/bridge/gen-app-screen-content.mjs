// hosts/shared/bridge/gen-app-screen-content.mjs —— ★★★App 三端对齐 · 阶段 1b（B5）+ A1
//   **SFC 产物 → 屏内容**（构建期生成；两端宿主共用）（2026-10-04）
//
// 【定位（★不含第二份实现——本仓"一处实现"纪律）】本脚本**不自己遍历路由/编译**——那件事
//   由 **CLI 的 `buildAppScreenContent`（`packages/cli/src/app-content.ts`，即 `proteus build --target <ios|android|harmony>`）**
//   做（唯一实现）。本脚本只做两件 fixture 专属的事：
//     ① 调用 CLI 构建器产出 `dist/app/<platform>/screen-content.json`；
//     ② 把它包成 bundle 可 import 的 `.ts`（`app-screen-content.generated.ts`）。
//   ⇒ 产品路径（proteus build --target <ios|android|harmony>）与装置路径（本脚本）**共用同一份转换逻辑**。
//
// 【为什么在构建期】`buildLayoutTemplate` 依赖 `@vue/compiler-sfc`（Node API）⇒ 端上跑不了。
//
// 用法：node hosts/shared/bridge/gen-app-screen-content.mjs [--project examples]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '../../..')
const OUT = path.join(HERE, 'app-screen-content.generated.ts')

const argv = process.argv.slice(2)
const projIdx = argv.indexOf('--project')
// ★批次 43：**App 端默认工程 = superapp**（独立应用落地三端）——可用 `PROTEUS_APP_PROJECT` 或 `--project X` 覆盖
const PROJECT = path.resolve(ROOT, projIdx >= 0 ? argv[projIdx + 1] : (process.env.PROTEUS_APP_PROJECT || 'superapp'))
const platIdx = argv.indexOf('--platform')
// ★按**具体平台**构建（标准做法；产物落 dist/app/<platform>/）——装置默认 android（bundle 两壳共用）
const PLATFORM = platIdx >= 0 ? argv[platIdx + 1] : 'android'

// ★唯一实现：CLI 的 App 屏内容构建器（`proteus build --target <ios|android|harmony>` 同一函数）
const cliMod = await import(pathToFileURL(path.join(ROOT, 'packages/cli/src/app-content.ts')).href)
const { buildAppScreenContent } = cliMod
// ★★★B1：运行期屏内容产物（tpl/table/events/handlers/data）——App 壳走统一运行期（交互/响应式/导航）
const rtMod = await import(pathToFileURL(path.join(ROOT, 'packages/cli/src/app-runtime-content.ts')).href)
const { buildAppRuntimeContent } = rtMod

const r = await buildAppScreenContent(PROJECT, PLATFORM)
const content = JSON.parse(fs.readFileSync(r.outFile, 'utf-8'))

const rt = await buildAppRuntimeContent(PROJECT, PLATFORM)
const runtimeContent = JSON.parse(fs.readFileSync(rt.outFile, 'utf-8'))

// 批次 43（superapp 独立应用）：从项目统一导航产物提取**屏注册表**（screens/tabNames + tab 标题）——
//   供 App 端**真实应用入口**（路由栈 + tab）消费。共一份路由树（与 Web/MP 同源）。
//   ★★★修（本批 · 决策 #795）：路径必须 honor `proteus.config.ts` 的 `router.routesOutput`——
//     此前硬编码 `PROJECT/router/auto-routes.ts`，而工程可配为 `src/router/auto-routes.ts`
//     （demos/dactyl 即此形态；create-proteus 模板缺省也是 `src/router/`）⇒ 注册表静默提取失败
//     （只打一行 ⚠ 后继续）⇒ boot 报「屏注册表为空」、整机白屏（本轮真机在模拟器上抓到）。
//     唯一实现 = CLI 的 `resolveAppRoutes`（#664 起它已是 routesOutput 的唯一解析处——不许第二份）。
const { resolveAppRoutes } = await import(pathToFileURL(path.join(ROOT, 'packages/cli/src/app-routes.ts')).href)
const autoRoutesPath = (await resolveAppRoutes(PROJECT)).file
let registry = { screens: {}, tabNames: [], tabLabels: {}, indexName: '', routes: [] }
try {
  const arMod = await import(pathToFileURL(autoRoutesPath).href)
  const screens = arMod.screens ?? {}
  const tabNames = arMod.tabNames ?? []
  const tabLabels = {}
  for (const rr of (arMod.routes ?? [])) {
    if (rr.meta && rr.meta.title) tabLabels[rr.name] = rr.meta.title
  }
  // ★★优先 `index`（与 Web RouterView 缺省回退 / MP pages[0]=index 同口径）——
  //   否则 App 落地页会随 routes 字母序漂移（实测：landed on background-position）。
  const indexName = (screens && screens['index']) ? 'index'
    : (Object.keys(screens)[0] ?? ((arMod.routes && arMod.routes[0] && arMod.routes[0].name) || ''))
  // ★真实应用入口用 createRouter(routes, { adapter })（与 Web/MP 同形）⇒ 共带 routes
  registry = { screens, tabNames, tabLabels, indexName, routes: arMod.routes ?? [] }
} catch (e) {
  console.log('[gen-app-screen-content] ⚠ 屏注册表提取失败（跳过）：' + String(e))
}

const header = `// AUTO-GENERATED by hosts/shared/bridge/gen-app-screen-content.mjs —— 勿手改
// ★★★App 三端对齐 · 阶段 1b（B5）+ A1：**项目路由 → 真实页面 SFC → 编译器 → 屏内容**。
//   来源工程：${path.relative(ROOT, PROJECT)}（router/auto-routes.ts；逻辑在 CLI 的 buildAppScreenContent）
//   内容确定（无时间戳）；两端宿主共用同一 bundle 入口。
//   屏名 → ScreenContent（来自真实 SFC 模板；CSS class 展开属缺口 C1——眼下主要是结构 + inline style）
/* eslint-disable */
import type { ScreenContent } from '../../../packages/render-backend/src/screen-executor'
export const APP_SCREEN_CONTENT: Record<string, ScreenContent> = ${JSON.stringify(content, null, 2)}

// 批次 43：**屏注册表**（来源项目 router/auto-routes.ts；screens/tabNames/tab 标题）——
//   App 端真实应用入口据此装配路由栈与 tab。与 Web/MP 同一棵路由树。
export const APP_SCREEN_REGISTRY = ${JSON.stringify(registry, null, 2)}

// ★★★B1：**运行期屏内容**（每屏 tpl/table/events/handlers/data）——App 壳经统一运行期
//   （createScreenRuntime：实例化 + 订阅 + 手势派发）驱动；交互/响应式/导航全在此产物里。
export const APP_RUNTIME_CONTENT = ${JSON.stringify(runtimeContent, null, 2)}
`
fs.writeFileSync(OUT, header)
console.log(
  `[gen-app-screen-content] ✅ ${path.relative(ROOT, OUT)}（编译 ${r.compiled} 页 / 跳过 ${r.skipped}；运行期 ${rt.compiled} 页）`,
)
const uniq = [...new Set(r.diagnostics)]
if (uniq.length) {
  console.log(`[gen-app-screen-content] ⚠ ${uniq.length} 类诊断（如实暴露——多为 CSS class / 不支持语法）：`)
  for (const d of uniq.slice(0, 10)) console.log(`    · ${d}`)
  if (uniq.length > 10) console.log(`    …另有 ${uniq.length - 10} 类`)
}
