// hosts/shared/bridge/gen-app-screen-content.mjs —— ★★★App 三端对齐 · 阶段 1b（B5）
//   **SFC 产物 → 屏内容**（构建期生成；两端宿主共用）（2026-10-04）
//
// 【它解决什么】阶段 1a 的 app-stack 装置用**手写节点**当屏内容（证明链路）；
//   本脚本用**真实 SFC**（经编译器 `buildLayoutTemplate`）+ 转换器
//   `screenContentFromLayoutTemplate` 产出**真产物**，写进生成模块供 bundle import。
//   ⇒ 端上跑的是「SFC → 编译器 → 屏内容 → 内核树」这条**真链**，不是手写 stub。
//
// 【为什么要在构建期（不能在端上）】`buildLayoutTemplate` 依赖 `@vue/compiler-sfc`（Node API）
//   ⇒ 进不了 QuickJS。与既有 `gen-vapor-fixture.mjs` 同一形态：构建期编译、产物下发。
//
// 【产物】`hosts/shared/bridge/app-screen-content.generated.ts`（export const APP_SCREEN_CONTENT）
//
// 【诚实边界】演示 SFC 用 **inline style**（App 折叠面只吃 inline style / 结构化 paint——
//   CSS class 展开属缺口 C1，未做）。生成内容按屏名替换标题文本（同源模板、不同文案）。
//
// 用法：node hosts/shared/bridge/gen-app-screen-content.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildLayoutTemplate } from '@proteus-vue/compiler'
import { screenContentFromLayoutTemplate } from '@proteus-vue/render-backend'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(HERE, 'app-screen-content.generated.ts')

/** 演示页 SFC（工作台形态：标题栏 + 文案 + 卡片；全 inline style——App 折叠面） */
function demoSfc(title) {
  return `<template>
  <view style="width: 100%; flex-direction: column; padding-top: 24; padding-left: 16; padding-right: 16">
    <view style="height: 56; flex-direction: row; align-items: center; background-color: #5B5BD6; border-radius: 12; padding-left: 16">
      <text style="color: #FFFFFF; font-size: 20">${title}</text>
    </view>
    <view style="height: 120; margin-top: 12; background-color: #FFFFFF; border-radius: 12" />
    <view style="height: 72; margin-top: 12; background-color: #F2F3F6; border-radius: 12" />
  </view>
</template>
<script setup lang="ts">
const unused = true
</script>`
}

/** 屏名 → 内容（与项目路由的屏名对齐；未命中的屏用 default） */
export function generateAppScreenContent() {
  const names = ['index', 'messages', 'mine', 'home', 'detail', 'third', 'r-home', 'r-detail', 'r-user']
  const out = {}
  const diagnostics = []
  for (const name of names) {
    const r = buildLayoutTemplate(demoSfc(name === 'default' ? '页面' : `${name} 页`), `${name}.vue`)
    if (!r.ok) {
      diagnostics.push(`${name}: 模板编译失败`)
      continue
    }
    out[name] = screenContentFromLayoutTemplate(r.template, { width: 390, height: 844 })
    // 收集不支持项诊断（如实暴露——不静默）
    for (const d of r.diagnostics) diagnostics.push(`${name}: ${d.code} ${d.message}`)
  }
  return { out, diagnostics }
}

const { out, diagnostics } = generateAppScreenContent()
const header = `// AUTO-GENERATED by hosts/shared/bridge/gen-app-screen-content.mjs —— 勿手改
// ★★★App 三端对齐 · 阶段 1b（B5）：**SFC 产物 → 屏内容**（编译器 buildLayoutTemplate + 转换器
//   screenContentFromLayoutTemplate）。内容确定（无时间戳）；两端宿主共用同一 bundle 入口。
//   屏名 → ScreenContent（来自真实 SFC 模板，inline style；CSS class 展开属缺口 C1）
/* eslint-disable */
import type { ScreenContent } from '../../../packages/render-backend/src/screen-executor'
export const APP_SCREEN_CONTENT: Record<string, ScreenContent> = ${JSON.stringify(out, null, 2)}
`
fs.writeFileSync(OUT, header)
console.log(`[gen-app-screen-content] ✅ ${path.relative(HERE, OUT)}（${Object.keys(out).length} 屏）`)
if (diagnostics.length) {
  // 去重后打印（诊断可能重复很多次）
  const uniq = [...new Set(diagnostics)]
  console.log(`[gen-app-screen-content] ⚠ ${uniq.length} 类模板诊断：`)
  for (const d of uniq.slice(0, 8)) console.log(`    · ${d}`)
}
