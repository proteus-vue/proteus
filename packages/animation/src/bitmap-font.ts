/** 点阵产物：一个字符矩阵 + 亮像素清单（行优先序） */
export interface TextBitmap {
  /** 列数（**最长一行的像素列**；多行时短行在块内**逐行居中**） */
  width: number
  /** 行数（单行恒为 7；多行 = `行数 × 7 + 行间空隙`） */
  height: number
  /** 亮像素清单（行优先；坐标为**字符矩阵坐标**，非屏幕坐标） */
  lit: ReadonlyArray<{ x: number; y: number }>
  /** 原文字（大写化后——供报告/探针回显；含 `\n`） */
  text: string
}

/** 字距（列）：字符宽 5 + 间隔 1 */
export const GLYPH_ADVANCE = 6
/** 字形高度（行） */
export const GLYPH_HEIGHT = 7
/** 多行的行间空隙（行）——紧凑但不断笔（真机截图实测：空隙 1 行时两行不粘） */
export const LINE_GAP = 1

/**
 * 把文本排成点阵（**纯函数**）
 *
 * - 支持 `\n` 多行：每行独立排版、**在块内居中**（"800" 顶在 "TILES" 上的构图）——
 *   单行太宽时（如 9 字 53 列）点阵会很小，多行是"把字做大"的唯一途径（列数减半 ⇒ 点距翻倍）
 * - 未知字符按空格处理（**不抛错**——"某个字没进字库"不该让整场动画失败；
 *   由调用方通过 `lit.length === 0` 发现"全空"这类输入错误）
 * - 小写转大写（本字库只有大写形态）
 */
export function textBitmap(text: string): TextBitmap {
  const up = text.toUpperCase()
  const lines = up.split('\n')
  // 每行的字形列宽（以像素列计：末字符右侧不留字距）
  const lineWidth = (s: string): number => (Math.max(s.length, 1) - 1) * GLYPH_ADVANCE + 5
  const widths = lines.map(lineWidth)
  const width = Math.max(...widths, 5)
  const height = lines.length * GLYPH_HEIGHT + (lines.length - 1) * LINE_GAP
  const lit: Array<{ x: number; y: number }> = []
  lines.forEach((line, li) => {
    // ★短行在块内居中（否则多行会左对齐——"800" 贴左边，"TILES" 贴右边，构图散）
    const xBase = Math.floor((width - widths[li]!) / 2)
    const yBase = li * (GLYPH_HEIGHT + LINE_GAP)
    for (let ci = 0; ci < line.length; ci++) {
      const ch = line[ci]!
      const glyph = FONT_5X7[ch] ?? FONT_5X7[' ']!
      const x0 = xBase + ci * GLYPH_ADVANCE
      for (let y = 0; y < GLYPH_HEIGHT; y++) {
        const row = glyph[y] ?? '.....'
        for (let x = 0; x < 5; x++) {
          if (row[x] === '#') lit.push({ x: x0 + x, y: yBase + y })
        }
      }
    }
  })
  return { width, height, lit, text: up }
}
